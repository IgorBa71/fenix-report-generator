def render_header(qualification, stage_name):
    """qualification: client["qualification"] — name, company, diagnosis_date,
    report_number, urgency, decisionMaker (+ decisionMakerOther, если 'Другое')."""
    decision = qualification.get("decisionMaker", "—")
    if decision == "Другое" and qualification.get("decisionMakerOther"):
        decision = qualification["decisionMakerOther"]

    return (
        f'СКРИПТ КОНСУЛЬТАЦИИ · Отчёт №{qualification.get("report_number", "—")}\n'
        f'Клиент: {qualification.get("name", "—")}\n'
        f'Компания: {qualification.get("company", "—")}\n'
        f'Стадия: {stage_name}\n'
        f'Дата диагностики: {qualification.get("diagnosis_date", "—")}\n'
        f'Готовность действовать: {qualification.get("urgency", "—")}\n'
        f'Принимает решение: {decision}'
    )


