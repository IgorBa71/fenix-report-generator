def render_maturity_section(flow_b, stage_id, primary_type):
    """flow_b: diagnose_result["поток_б"] целиком (нужны individual_top5 и
    maturity). stage_id: текущая Стадия клиента (int) — для {n} в текстах."""
    top5 = flow_b["individual_top5"]
    maturity = flow_b["maturity"]
    note = maturity["note"]
    later = maturity["later_stage_challenges"]
    earlier = maturity["earlier_stage_challenges"]

    lines = [MATURITY_TOP5_INTRO]
    lines.extend(f'{i + 1}.\t«{c}»' for i, c in enumerate(top5))
    lines.append("")

    if note == "опережает_стадию":
        template = MATURITY_AHEAD[primary_type]
        lines.append(template.format(challenges=_join_ru(later), n=stage_id))
    elif note == "отстаёт_от_стадии":
        template = MATURITY_BEHIND[primary_type]
        lines.append(template.format(challenges=_join_ru(earlier), n=stage_id))
    elif note == "смешанная_картина":
        template = MATURITY_MIXED[primary_type]
        lines.append(template.format(earlier=_join_ru(earlier), later=_join_ru(later), n=stage_id))
    else:  # соответствует_стадии
        template = MATURITY_MATCH[primary_type]
        lines.append(template.format(n=stage_id))

    return "\n".join(lines)


