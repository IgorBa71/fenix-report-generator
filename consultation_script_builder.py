# ГЛОБАЛЬНОЕ ПРАВИЛО ЧТЕНИЯ: «каждое предложение — с новой строки».
#
# Вместо того чтобы вручную переразбивать десятки f-строк по всему файлу
# (риск разъехаться при следующей правке текста), это применяется ОДНИМ
# финальным проходом по уже собранному тексту каждого Раздела — см. reflow()
# и её вызов в конце build_full_script(). Не трогает: заголовки ("=" * 70),
# маркеры слайдов [→ ...]/[⚠ ...], буллеты (•), нумерованные списки (1. «..»),
# пустые строки-разделители.
# ---------------------------------------------------------------------------

_ABBREVIATIONS = ("т.е.", "т.д.", "т.п.", "др.", "проф.", "им.", "г.", "гг.", "руб.")

_SENTENCE_SPLIT_RE = re.compile(r'(?<=[.!?…])(?<!т\.е\.)(?<!т\.д\.)(?<!т\.п\.)\s+(?=[А-ЯЁA-Z«"(])')


def _split_into_sentences(line):
    """Разбивает ОДНУ строку прозы на предложения. Эвристика: разрыв после
    ./!/?/… перед следующей заглавной буквой/кавычкой, кроме известных
    сокращений (т.е., т.д., т.п.) — для них разрыв подавлен через lookbehind."""
    pieces = _SENTENCE_SPLIT_RE.split(line)
    return [p.strip() for p in pieces if p.strip()]


def _is_reflow_exempt(stripped):
    """Строки-разметка (заголовки/маркеры/списки/буллеты) — не трогаем."""
    if not stripped:
        return True
    if stripped.startswith(("=", "[→", "[⚠", "•", "-\t", "---")):
        return True
    if re.match(r'^\d+[.)]\s', stripped):
        return True
    if stripped.isupper():
        return True
    return False


def reflow(text):
    """Применяет правило «каждое предложение — с новой строки» ко всему
    прозаическому тексту в text, оставляя разметку (см. _is_reflow_exempt)
    нетронутой."""
    out_lines = []
    for line in text.split("\n"):
        stripped = line.strip()
        if _is_reflow_exempt(stripped):
            out_lines.append(line)
            continue
        out_lines.extend(_split_into_sentences(line))
    return "\n".join(out_lines)


