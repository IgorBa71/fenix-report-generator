def render_closing_section(qualification):
    """qualification: client["qualification"] — urgency, decisionMaker
    (+ decisionMakerOther, если 'Другое')."""
    urgency = qualification.get("urgency")
    decision = qualification.get("decisionMaker")

    lines = [slide_marker("closing").rstrip("\n")]
    framing = URGENCY_FRAMING.get(urgency)
    if framing:
        lines.append(framing)
        lines.append("")

    if decision == "Другое":
        other = qualification.get("decisionMakerOther", "").strip()
        if other:
            lines.append(
                f'Вы отметили, что решение принимается так: «{other}» — расскажите, '
                f'пожалуйста, подробнее об этом процессе, чтобы я мог предложить '
                f'подходящий следующий шаг.'
            )
        else:
            lines.append("Расскажите, пожалуйста, как у Вас обычно принимаются такие решения?")
    else:
        ask = DECISION_MAKER_ASK.get(decision)
        if ask:
            lines.append(ask)

    lines.append("")
    lines.append("Что скажете?")
    return "\n".join(lines)


def render_objections_block(section9, primary_type, all_kse_ordered=None, qualification=None):
    numbered_items = [
        ("«ДОРОГО» / «СОКРАТИТЬ БЮДЖЕТ»",
         phrase_objection_price(section9, primary_type, all_kse_ordered)),
        ("«НУЖНО ПОДУМАТЬ / ОБСУДИТЬ С ПАРТНЁРОМ»",
         phrase_objection_think_it_over(section9, primary_type)),
    ]
    for label, core in OBJECTIONS_CORE.items():
        numbered_items.append((f'«{label}»', core))
    numbered_items.append(("«Хочу сам сначала попробовать»",
                            phrase_objection_try_myself(all_kse_ordered)))
    if all_kse_ordered and "Сильная Управленческая команда" in all_kse_ordered:
        numbered_items.append(("Дополнительный вопрос про Программу «Сильная Управленческая команда» (FAQ)",
                                phrase_objection_smt_faq()))

    parts = []
    for i, (label, text) in enumerate(numbered_items, start=1):
        parts.append(f'{i}. {label}')
        parts.append(text)
        parts.append("")

    if qualification:
        parts.append("--- ЗАКРЫТИЕ ---\n")
        parts.append(render_closing_section(qualification))

    return "\n".join(parts)


