STAFFING_GAP_KSE = ("Организационная структура", "Сильная Управленческая команда")


def build_fact_summary_staffing_gap(gap_parts):
    """gap_parts: подмножество ['Менеджеров', 'Высших руководителей'] — кого именно
    не хватает по нормативу Вашей Стадии (Раздел 1 Отчёта)."""
    gap_text = " и ".join(gap_parts) if gap_parts else "управленческого состава"
    return f'в Разделе 1 у Вас выявлен кадровый разрыв по количеству {gap_text}'


def render_challenges_kse_section(top_kse_rows, client_challenge_scores, area_deficit,
                                   mapping, flow_a, primary_type):
    """top_kse_rows: [kse_name, ...] — приоритетные КСЭ из ОСТАЛЬНЫХ 10 (не
    "Критерии роста бизнеса" — тот обрабатывается в Части 1 отдельно).

    Для каждого КСЭ: если это "Организационная структура"/"Сильная Управленческая
    команда" И есть кадровый разрыв (flow_a managers_gap/leaders_gap > 0) —
    используем обоснование через кадровый разрыв (приоритетный случай, как в
    Отчёте). Иначе — обычная цепочка Вызовы + Непреложные правила ->
    _find_symptom_challenges/_find_deficit_areas (РЕАЛЬНАЯ логика
    report_text_generator.py) -> КСЭ."""
    parts = []
    for i, kse_name in enumerate(top_kse_rows):
        has_staffing_gap = (
            kse_name in STAFFING_GAP_KSE
            and (flow_a.get("managers_gap", 0) > 0 or flow_a.get("leaders_gap", 0) > 0)
        )
        if has_staffing_gap:
            gap_parts = []
            if flow_a.get("managers_gap", 0) > 0:
                gap_parts.append("Менеджеров")
            if flow_a.get("leaders_gap", 0) > 0:
                gap_parts.append("Высших руководителей")
            fact_summary = build_fact_summary_staffing_gap(gap_parts)
            challenges, areas = None, None
        else:
            challenges = _find_symptom_challenges(kse_name, client_challenge_scores, mapping)
            areas = _find_deficit_areas(kse_name, area_deficit, mapping)
            fact_summary = build_fact_summary(challenges, areas)

        if i == 0:
            parts.append(phrase_kse_justification(kse_name, fact_summary, primary_type, challenges, areas))
        else:
            parts.append(phrase_kse_justification_followup(kse_name, fact_summary, primary_type, challenges, areas))
        tagline = render_kse_tagline(kse_name)
        if tagline:
            parts.append(tagline)
        parts.append("")
    return "\n".join(parts)


