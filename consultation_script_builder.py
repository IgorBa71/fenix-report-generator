def format_rub(amount):
    """1234567 -> '1 234 567 руб.' (разделитель тысяч — пробел, как и везде в проекте)."""
    return f'{amount:,.0f}'.replace(',', ' ') + ' руб.'


def compute_bundle_fork(all_kse_ordered, stage_id, bundle_kse_covered, bundle_weeks, bundle_price,
                         individual_program_weeks, individual_program_prices, min_intersection=4):
    """all_kse_ordered: список рекомендованных клиенту КСЭ (без "Критерии роста
    бизнеса" — он в бандл не входит). bundle_kse_covered: set КСЭ, которые
    покрывает бандл "Возрождение малого бизнеса". individual_program_weeks /
    individual_program_prices: {kse_name: недель / цена в рублях (число)} для
    отдельных Программ, входящих в пересечение. bundle_price: цена бандла в
    рублях (число). Возвращает dict с данными развилки, или None, если условия
    показа не выполнены (не Стадия 1-3, или пересечение меньше порога)."""
    if stage_id not in (1, 2, 3):
        return None
    intersection = sorted(set(all_kse_ordered) & set(bundle_kse_covered))
    if len(intersection) < min_intersection:
        return None
    individual_weeks_sum = sum(individual_program_weeks.get(k, 0) for k in intersection)
    individual_price_sum = sum(individual_program_prices.get(k, 0) for k in intersection)
    return {
        "intersection": intersection,
        "total": len(bundle_kse_covered),
        "individual_weeks_sum": individual_weeks_sum,
        "individual_price_sum": individual_price_sum,
        "bundle_weeks": bundle_weeks,
        "bundle_price": bundle_price,
    }


