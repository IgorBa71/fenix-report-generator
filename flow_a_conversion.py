def _group_ranks_by_style(group_num, group_ranks):
    """group_ranks: {statement_text: rank_1_to_6} -> {style: rank}"""
    statements = MANAGEMENT_STYLES_STATEMENTS[group_num]
    return {STYLE_BY_POSITION[i]: group_ranks[stmt] for i, stmt in enumerate(statements)}


def compute_management_styles(group1_ranks, group2_ranks, group3_ranks):
    """
    group{N}_ranks: {statement_text: rank_1_to_6}
    Возвращает {"Основной": ..., "Второстепенный": ..., "Дополнительный": ...}
    """
    g1 = _group_ranks_by_style(1, group1_ranks)
    g2 = _group_ranks_by_style(2, group2_ranks)
    g3 = _group_ranks_by_style(3, group3_ranks)

    totals = {style: g1[style] + g2[style] + g3[style] for style in STYLE_BY_POSITION.values()}
    # наибольшая сумма -> Основной (подтверждено примером в файле-ключе)
    ranked = sorted(totals, key=totals.get, reverse=True)
    return {
        "Основной": ranked[0],
        "Второстепенный": ranked[1],
        "Дополнительный": ranked[2],
    }


