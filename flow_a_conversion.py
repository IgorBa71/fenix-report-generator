# 9 вопросов идут в опросе тремя блоками по 3 (в этом же порядке показа):
#   Группа 1 (вопросы 1-3) -> определяет уровень с Доминирующей ролью
#   Группа 2 (вопросы 4-6) -> определяет уровень с Поддерживающей ролью
#   Группа 3 (вопросы 7-9) -> определяет уровень с Вспомогательной ролью
# Внутри каждой группы клиент отвечает на 3 вопроса, выбирая уровень
# (Руководство/Менеджеры/Сотрудники). Роль присваивается уровню, который
# клиент выбрал чаще других ВНУТРИ этой конкретной группы (мода из 3 ответов),
# а НЕ по общей частоте среди всех 9 вопросов сразу — это ключевое отличие
# от предыдущей черновой версии.

MODALITY_GROUP_ROLES = ["Доминирующая", "Поддерживающая", "Вспомогательная"]


def compute_modality(nine_answers):
    """
    nine_answers: список из 9 строк — 'Руководство'/'Менеджеры'/'Сотрудники',
    строго в порядке показа вопросов в опросе (как в Разделе 4).
    """
    if len(nine_answers) != 9:
        raise ValueError("Ожидается ровно 9 ответов (3 группы по 3 вопроса)")

    result = {}
    for i, role in enumerate(MODALITY_GROUP_ROLES):
        group_answers = nine_answers[i * 3:(i + 1) * 3]
        # мода — уровень, выбранный чаще других внутри этой группы
        counts = {}
        for a in group_answers:
            counts[a] = counts.get(a, 0) + 1
        winner = max(counts, key=counts.get)
        result[winner] = role
    return result


